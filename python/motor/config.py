#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""电机子系统配置（纯数据模块）。

边界：本模块是依赖树的叶子——不导入包内其它任何模块，只被其它模块导入。
职责：集中全部可调常量（引脚、机械参数、整定参数、IPC 路径），
      使硬件映射与控制参数只有一个权威来源。
"""
# --------------------------------------------------------------------------
# 一、GPIO 引脚（P1 排针，GPIO5 bank；编号为 Linux 全局 GPIO 号）
# --------------------------------------------------------------------------
GPIO = "/sys/class/gpio"

# 每路电机：pwm 调速脚 / in1,in2 方向脚 / ea,eb 编码器 A、B 相
# inv：换向（软件取反方向电平）；enc_inv：编码器计数方向取反
MOTORS = {
    "A": dict(pwm=176, in1=178, in2=179, ea=182, eb=183, inv=False, enc_inv=True),
    "B": dict(pwm=177, in1=180, in2=181, ea=184, eb=185, inv=False, enc_inv=False),
}
MOTOR_NAMES = ("A", "B")

# 编码器寄存器自校准用的方向脚顺序 -> 图案 (0,1,1,0)：AIN1,AIN2,BIN1,BIN2
CAL_PINS = [MOTORS[n][k] for n in MOTOR_NAMES for k in ("in1", "in2")]
CAL_PATTERN = (0, 1, 1, 0)

# --------------------------------------------------------------------------
# 二、机械与编码器参数（MG310 + TB6612）
# --------------------------------------------------------------------------
PPR = 13.0            # 编码器线数（电机轴）
GEAR = 20.409         # 减速比
MULT = 4              # 4 倍频
CPR = PPR * GEAR * MULT      # 输出轴每圈计数 ≈1061.3
DEBOUNCE_S = 0.00005  # 编码器状态确认窗（真实状态间隔 ≥290µs，毛刺对 <100µs）
GPIO5_BASE = 0x21900000  # gpiochip5 parent platform/21900000.gpio
REG_CANDIDATES = (0x50, 0x58, 0x00, 0x64, 0x54)   # 电平寄存器偏移候选

# --------------------------------------------------------------------------
# 三、软件 PWM
# --------------------------------------------------------------------------
PWM_HZ = 1000         # 软件 PWM 频率（可被 --pwm-hz 覆盖）


def set_pwm_hz(hz):
    """运行时修改软件 PWM 频率（须在 SoftPwm 实例化之前调用）。"""
    global PWM_HZ
    hz = float(hz)
    if hz <= 0:
        raise ValueError("pwm hz 必须 > 0")
    PWM_HZ = hz


# --------------------------------------------------------------------------
# 四、速度环 / 位置环整定参数
# --------------------------------------------------------------------------
FF_DUTY = 1.38           # 前馈：duty/rpm（开环标定 150~1000 duty 平均斜率）
DB_DUTY = 60             # 死区补偿：维持转动所需最小占空比（起动力矩靠积分顶上去）
KP, KI = 2.0, 0.2        # 速度环 PI（前馈承担主输出，PI 只做小幅修正）
I_CLAMP = 400            # 积分限幅（duty 单位）：预留负载变化的自适应权限
SLEW = 50                # 每拍(100ms)占空比最大变化：软启动+防猛冲
RPM_LPF_NEW = 0.6        # 测速低通：新值权重（旧值权重 = 1 - 该值）
POS_KP = 0.6             # 位置环比例（千分比 / count）
POS_EPS = 8              # 到位判据（count）
POS_ZONE = 60            # 进入脉冲爬行区（count）
POS_PULSE_DUTY = 60      # 脉冲占空比（自适应上限 400）
POS_PULSE_MS = 0.04      # 脉冲间隔（秒）
POS_LIMIT = 400          # 位置环比例输出限幅（千分比）
POS_PULSE_MAX = 400      # 脉冲占空比自适应上限
POS_PULSE_STEP = 40      # 脉冲不动时的加力步长
POS_COOL = 0.05          # 过冲后刹车保持时间（秒）
POS_TIMEOUT = 30         # 位置模式超时（秒）

# --------------------------------------------------------------------------
# 五、控制节拍
# --------------------------------------------------------------------------
CTRL_DT = 0.01           # 控制环基础节拍（秒）
SPEED_WIN = 10           # 每 N 拍计算一次速度（10 × 10ms = 100ms）

# --------------------------------------------------------------------------
# 六、进程间通信
# --------------------------------------------------------------------------
SOCK = "/run/motor_ctl.sock"

# --------------------------------------------------------------------------
# 七、驱动芯片使能（STBY）
# --------------------------------------------------------------------------
# 电机功率全部来自外部 12V（D153B VM），与板端电源无关。
# 默认 STBY 硬接模块 3V3（模块自供电）；若改接板端 GPIO 做软件急停，填编号（如 186/224）
STBY_GPIO = None
